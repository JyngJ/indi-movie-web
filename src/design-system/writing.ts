/** 라이팅 규범 — 화면에 적히는 한국어 문장의 약속.
 *
 *  토큰·컴포넌트 값은 코드와 피그마에서 생성되지만 문장은 생성할 수 없어 여기에 손으로 적는다.
 *  이 파일이 단 하나의 진실이다 — /design-system/foundations/writing 페이지와
 *  /design-system/llms-writing.txt 둘 다 여기서 렌더한다. 문서를 따로 쓰면 그것이 둘째 진실이 된다.
 *
 *  규범은 2026-08-23 기준 코드에 실제로 적힌 카피를 전수 조사해서 뽑았다. 이미 일관된 것은
 *  그대로 굳히고, 갈라져 있던 것(어미·띄어쓰기·마침표·로딩 문구)은 한쪽으로 정했다.
 *  정한 근거는 각 항목의 why에 적는다 — 근거가 없으면 다음 사람이 같은 논쟁을 다시 한다. */

export interface WritingExample {
  /** 맞는 예 */
  good: string
  /** 틀린 예 — 가능하면 실제 코드에 있던(있는) 문장을 쓴다 */
  bad?: string
}

export interface WritingRule {
  id: string
  title: string
  /** 규칙 한 문장. 명령형으로 적는다 */
  rule: string
  /** 왜 이렇게 정했는가 */
  why?: string
  examples?: WritingExample[]
  /** 용어 ↔ 뜻 짝. 버튼 어휘표처럼 문장으로 풀면 뭉치는 것 */
  table?: [string, string][]
}

export interface WritingSection {
  id: string
  title: string
  lead: string
  rules: WritingRule[]
}

